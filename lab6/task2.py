def average(a, b, c):
    return (a + b + c) / 3

# Кемінде 3 тест қолдану
res1 = average(4, 7, 10)
print(f"Орташа мән: {res1:.2f}")  # Нәтиже: 7.00

res2 = average(10, 20, 35)
print(f"Орташа мән: {res2:.2f}")  # Нәтиже: 21.67

res3 = average(5, 5, 6)
print(f"Орташа мән: {res3:.2f}")  # Нәтиже: 5.33